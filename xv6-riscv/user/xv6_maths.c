static float powf_int(float base, int exp) {
    float result = 1.0f;
    float b = base;
    int e = exp;

    if (e < 0) {
        b = 1.0f / b;
        e = -e;
    }

    while (e > 0) {
        if (e & 1) result *= b;
        b *= b;
        e >>= 1;
    }
    return result;
}

float xv6_floorf(float x) {
    if (x >= 0) return (float)((int)x);
    int i = (int)x;
    return (x == (float)i) ? x : (float)(i - 1);
}

float xv6_fmodf(float x, float y) {
    if (y == 0.0f) return xv6_nan();
    float quotient = x / y;
    quotient = xv6_floorf(quotient);
    return x - quotient * y;
}

