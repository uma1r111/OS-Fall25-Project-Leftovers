float xv6_fabsf(float x) {
    unsigned int bits = xv6_f2u(x);
    bits &= 0x7FFFFFFFu;
    return xv6_u2f(bits);
}

float xv6_sqrtf(float x) {
    if (x < 0.0f) return xv6_nan();
    if (x == 0.0f) return 0.0f;
    if (xv6_isinf(x)) return xv6_infinity();
    if (xv6_isnan(x)) return xv6_nan();

    float y = (x >= 1.0f) ? x / 2.0f : 1.0f;
    const int MAX_ITER = 20;
    const float TOL = 1e-7f;

    for (int i = 0; i < MAX_ITER; i++) {
        float prev = y;
        y = 0.5f * (y + x / y);
        if (xv6_fabsf(y - prev) < TOL) break;
    }
    return y;
}

float xv6_expf(float x) {
    const float MAX_EXP = 88.72f;
    const float MIN_EXP = -87.33f;

    if (xv6_isnan(x)) return xv6_nan();
    if (xv6_isinf(x)) return (x > 0) ? xv6_infinity() : 0.0f;
    if (x > MAX_EXP) return xv6_infinity();
    if (x < MIN_EXP) return 0.0f;

    if (x < 0.0f) return 1.0f / xv6_expf(-x);

    int int_part = (int)x;
    float frac_part = x - (float)int_part;

    float scaled = frac_part * EXP_TABLE_SIZE;
    int index = (int)scaled;
    if (index < 0) index = 0;
    if (index >= EXP_TABLE_SIZE) index = EXP_TABLE_SIZE - 1;
    float remainder = scaled - (float)index;

    float exp_frac = EXP_TABLE[index] +
                     remainder * (EXP_TABLE[index + 1] - EXP_TABLE[index]);

    float exp_int = powf_int(XV6_E, int_part);
    return exp_int * exp_frac;
}

float xv6_logf(float x) {
    if (x < 0.0f) return xv6_nan();
    if (x == 0.0f) return -xv6_infinity();
    if (x == 1.0f) return 0.0f;
    if (xv6_isinf(x)) return xv6_infinity();
    if (xv6_isnan(x)) return xv6_nan();

    float y = 0.0f;
    if (x > 1.0f) {
        y = 1.0f;
        while (xv6_expf(y) < x) y += 1.0f;
    } else {
        y = -1.0f;
        while (xv6_expf(y) > x) y -= 1.0f;
    }

    const int MAX_ITER = 20;
    const float TOL = 1e-7f;

    for (int i = 0; i < MAX_ITER; i++) {
        float exp_y = xv6_expf(y);
        float delta = 2.0f * (x - exp_y) / (x + exp_y);
        y += delta;
        if (xv6_fabsf(delta) < TOL) break;
    }
    return y;
}

float xv6_powf(float base, float exponent) {
    if (base == 0.0f) {
        if (exponent == 0.0f) return 1.0f;
        if (exponent < 0.0f) return xv6_infinity();
        return 0.0f;
    }

    if (base == 1.0f || exponent == 0.0f) return 1.0f;
    if (exponent == 1.0f) return base;
    if (xv6_isnan(base) || xv6_isnan(exponent)) return xv6_nan();

    if (base < 0.0f) {
        int exp_int = (int)exponent;
        if (exponent == (float)exp_int) {
            float result = powf_int(base, exp_int);
            return result;
        }
        return xv6_nan();
    }

    return xv6_expf(exponent * xv6_logf(base));
}

float xv6_sinf(float x) {
    if (xv6_isnan(x) || xv6_isinf(x)) return xv6_nan();

    x = xv6_fmodf(x, 2.0f * XV6_PI);
    if (x > XV6_PI) x -= 2.0f * XV6_PI;
    if (x < -XV6_PI) x += 2.0f * XV6_PI;

    float result = x;
    float term = x;
    float x2 = x * x;
    const int MAX_TERMS = 15;

    for (int n = 1; n < MAX_TERMS; n++) {
        term *= -x2 / ((2.0f * n) * (2.0f * n + 1.0f));
        result += term;
        if (xv6_fabsf(term) < 1e-7f) break;
    }
    return result;
}

float xv6_cosf(float x) {
    if (xv6_isnan(x) || xv6_isinf(x)) return xv6_nan();

    x = xv6_fmodf(x, 2.0f * XV6_PI);
    if (x > XV6_PI) x -= 2.0f * XV6_PI;
    if (x < -XV6_PI) x += 2.0f * XV6_PI;

    float result = 1.0f;
    float term = 1.0f;
    float x2 = x * x;
    const int MAX_TERMS = 15;

    for (int n = 1; n < MAX_TERMS; n++) {
        term *= -x2 / ((2.0f * n - 1.0f) * (2.0f * n));
        result += term;
        if (xv6_fabsf(term) < 1e-7f) break;
    }
    return result;
}

float xv6_tanhf(float x) {
    if (xv6_isnan(x)) return xv6_nan();
    if (xv6_isinf(x)) return (x > 0) ? 1.0f : -1.0f;
    if (x > 10.0f) return 1.0f;
    if (x < -10.0f) return -1.0f;

    float epos = xv6_expf(x);
    float eneg = xv6_expf(-x);
    return (epos - eneg) / (epos + eneg);
}
